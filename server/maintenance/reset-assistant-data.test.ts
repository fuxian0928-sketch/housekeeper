import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {once} from 'node:events';
import express from 'express';
import {defaultAssistantPersona} from '../domain/memories/assistant-character.js';
import {assistantResetPlan,resetAssistantData} from './reset-assistant-data.js';

test('offline reset clears derived data and queues, keeps connections, and detaches old libraries',async t=>{
 process.env.AI_SECRETARY_DB_PATH=join(mkdtempSync(join(tmpdir(),'assistant-reset-')),'test.db');
 const {database:db,initializeDatabase,nowIso}=await import('../db.js');initializeDatabase();t.after(()=>db.close());
 const at=nowIso(),setting=db.prepare('INSERT OR REPLACE INTO app_settings(key,value,updated_at) VALUES(?,?,?)');
 setting.run('api_key','fixture-secret',at);setting.run('ai_model','fixture-model',at);setting.run('sync_enabled','1',at);setting.run('vault_path','external-originals',at);
 db.prepare("INSERT INTO projects(id,name,vault_path,source_path,created_at,updated_at) VALUES('p','旧项目','','',?,?)").run(at,at);
 db.prepare("INSERT INTO conversations(id,scope_type,title,created_at,updated_at) VALUES('c','memory','旧聊天',?,?)").run(at,at);
 db.prepare("INSERT INTO messages(id,conversation_id,role,content,created_at) VALUES('m','c','user','我喜欢茶。',?)").run(at);
 db.prepare("INSERT INTO memories(id,content,memory_type,status,source_label,created_at,updated_at) VALUES('memory','旧偏好','preference','confirmed','旧聊天',?,?)").run(at,at);
 assert.ok(assistantResetPlan(db).some(table=>table.name==='message_archive_fts'&&table.rows>0));
 const input={backupVerified:true,persona:defaultAssistantPersona,disabledWorkTools:['computer_action','create_document']};
 assert.throws(()=>resetAssistantData(db,{...input,backupVerified:false}),/备份/);
 db.exec('CREATE TABLE future_configuration(id TEXT PRIMARY KEY)');
 assert.throws(()=>resetAssistantData(db,input),/未分类/);
 assert.equal(db.prepare('SELECT COUNT(*) AS n FROM messages').get()?.n,1);
 db.exec('DROP TABLE future_configuration');
 const result=resetAssistantData(db,input);
 assert.equal(result.remainingUserRows,0,JSON.stringify(assistantResetPlan(db).filter(table=>table.rows>0)));assert.ok(assistantResetPlan(db).every(table=>table.rows===0));
 for(const [key,value] of [['api_key','fixture-secret'],['ai_model','fixture-model'],['sync_enabled','0'],['vault_path',''],['tool_enabled:computer_action','0'],['device_sync_suspended','1']])assert.equal(db.prepare('SELECT value FROM app_settings WHERE key=?').get(key)?.value,value);
 const {learnedContext}=await import('../domain/memories/learned-context.js');
 const context=learnedContext('之前喜欢什么',null);
 assert.deepEqual(context.userProfile.facts,[]);assert.deepEqual(context.experiences,[]);assert.deepEqual(context.recentStatements,[]);
 assert.equal(context.assistantPersona.profile.fictionalBackground.fictional,true);
 assert.equal(db.prepare('PRAGMA foreign_keys').get()?.foreign_keys,1);
 initializeDatabase();
 assert.equal(db.prepare('SELECT COUNT(*) AS n FROM messages').get()?.n,0);
 assert.equal(db.prepare('SELECT COUNT(*) AS n FROM memories').get()?.n,0);
 const {listSkillTools,executeSkillTool}=await import('../domain/skills/skill-tool-registry.js');
 assert.ok(listSkillTools().some(tool=>tool.name==='save_memory'&&tool.enabled));
 assert.ok(listSkillTools().some(tool=>tool.name==='search_documents'&&tool.enabled));
 assert.ok(listSkillTools().filter(tool=>tool.mode==='write'&&tool.enabled).every(tool=>['save_memory','replace_memory','forget_memory'].includes(tool.name)));
 setting.run('tool_enabled:create_document','1',at);
 await assert.rejects(async()=>executeSkillTool('create_document',{title:'不应写入',content:'不应写入'},{vaultPath:''}),/实际执行工作/);
 const {registerDeviceSyncRoutes}=await import('../api/device-sync.js');
 const app=express();app.use(express.json());registerDeviceSyncRoutes(app);
 const server=app.listen(0,'127.0.0.1');await once(server,'listening');t.after(()=>new Promise<void>(resolve=>server.close(()=>resolve())));
 const response=await fetch(`http://127.0.0.1:${(server.address() as {port:number}).port}/api/device-sync/manifest`,{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({deviceId:'old-device'})});
 assert.equal(response.status,409);assert.equal((await response.json()).code,'LIBRARY_IMPORT_SUSPENDED');
 assert.equal(db.prepare('SELECT COUNT(*) AS n FROM central_source_documents').get()?.n,0);
});
