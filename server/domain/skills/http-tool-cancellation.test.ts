import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {createServer} from 'node:http';
test('HTTP cancellation preserves unknown write evidence and blocks replay',async t=>{
 process.env.AI_SECRETARY_DB_PATH=join(mkdtempSync(join(tmpdir(),'http-outcome-')),'test.db');
 const {database,initializeDatabase}=await import('../../db.js');initializeDatabase();
 const {saveHttpTool,httpToolDefinitions,callHttpTool}=await import('./http-tools.js');
 const {executeSkillTool}=await import('./skill-tool-registry.js');
 const {saveToolPolicy,listToolRuns}=await import('./tool-controls.js');
 const {runSkillTools}=await import('./skill-executor.js');
 const {confirmAction}=await import('../../actions/action-service.js');
 let calls=0,onRequest:(()=>void)|undefined;let hold=false,held:import('node:http').ServerResponse|undefined,entered!:()=>void;
 const server=createServer((req,res)=>{calls++;onRequest?.();req.resume();if(req.url==='/hold'&&hold){held=res;entered();return;}if(req.url==='/drop'){res.destroy();return;}res.end(JSON.stringify({ok:true}));});
 await new Promise<void>(r=>server.listen(0,'127.0.0.1',r));t.after(()=>{server.closeAllConnections();server.close();database.close();});
 const port=(server.address() as {port:number}).port;
 saveHttpTool({name:'fixture',description:'test',method:'POST',url:`http://127.0.0.1:${port}/drop`,schema:{type:'object'}});
 const name=httpToolDefinitions()[0].name;saveToolPolicy(name,'auto');
 const pre=new AbortController();pre.abort();await assert.rejects(callHttpTool(name,{},pre.signal),{name:'AbortError'});assert.equal(calls,0);
 database.prepare("INSERT INTO conversations(id,scope_type,title,created_at,updated_at) VALUES('c','global','test','now','now')").run();
 const context={vaultPath:'central://documents'};
 let planning=0;const input={conversationId:'c',message:'test',skills:[],skillInstruction:'',context,complete:async()=>{planning++;return JSON.stringify({toolCalls:[{tool:name,arguments:{value:1}}]});}};
 const abort=new AbortController();onRequest=()=>abort.abort();
 await assert.rejects(runSkillTools({...input,signal:abort.signal}),{code:'TOOL_OUTCOME_UNKNOWN'});assert.equal(calls,1);assert.equal(planning,1);
 assert.equal((listToolRuns()[0] as any).status,'unknown');
 assert.equal((database.prepare('SELECT status FROM skill_tool_executions').get() as any).status,'unknown');
 onRequest=undefined;await assert.rejects(runSkillTools(input),{code:'TOOL_OUTCOME_UNKNOWN'});assert.equal(calls,1,'next turn cannot repeat the same uncertain write');
 await assert.rejects(Promise.resolve().then(()=>executeSkillTool(name,{value:1},context)),{code:'TOOL_OUTCOME_UNKNOWN'});assert.equal(calls,1,'direct tool entry also blocks unknown calls');
 database.prepare("INSERT INTO conversations(id,scope_type,title,created_at,updated_at) VALUES('other','global','test','now','now')").run();
 await assert.rejects(runSkillTools({...input,conversationId:'other'}),{code:'TOOL_OUTCOME_UNKNOWN'});assert.equal(calls,1,'new conversations cannot bypass dispatch guard');
 saveToolPolicy(name,'confirm');const pending=await runSkillTools({...input,complete:async()=>JSON.stringify({toolCalls:[{tool:name,arguments:{value:2}}]})});
 await assert.rejects(Promise.resolve().then(()=>confirmAction(pending.pending[0].id)),{code:'TOOL_OUTCOME_UNKNOWN'});
 assert.throws(()=>confirmAction(pending.pending[0].id),/已经执行|关闭/);assert.equal(calls,2);
 assert.throws(()=>executeSkillTool(name,{},context,pre.signal),{name:'AbortError'});assert.equal(calls,2);
 saveHttpTool({name:'read',description:'test',method:'GET',url:`http://127.0.0.1:${port}/drop`,schema:{type:'object'}});
 const readName=httpToolDefinitions().find(t=>t.description.startsWith('read'))!.name;
 await assert.rejects(callHttpTool(readName,{}),(error:any)=>error.code!=='TOOL_OUTCOME_UNKNOWN');
 saveHttpTool({name:'success',description:'test',method:'POST',url:`http://127.0.0.1:${port}/ok`,schema:{type:'object'}});
 const successName=httpToolDefinitions().find(t=>t.description.startsWith('success'))!.name;
 assert.deepEqual(await callHttpTool(successName,{}),{ok:true});
 saveHttpTool({name:'hold',description:'test',method:'POST',url:`http://127.0.0.1:${port}/hold`,schema:{type:'object'}});
 const holdName=httpToolDefinitions().find(t=>t.description.startsWith('hold'))!.name;saveToolPolicy(holdName,'auto');
 const heldInput={...input,conversationId:'other',complete:async()=>JSON.stringify({toolCalls:[{tool:holdName,arguments:{}}]})};
 const received=new Promise<void>(r=>entered=r);hold=true;const owner=runSkillTools(heldInput);await received;
 await assert.rejects(runSkillTools(heldInput),{code:'TOOL_IN_PROGRESS'});
 hold=false;held!.end(JSON.stringify({ok:true}));await owner;
 assert.equal((database.prepare("SELECT COUNT(*) AS count FROM skill_tool_executions WHERE tool_name=? AND status='unknown'").get(holdName) as any).count,0,'busy duplicate must not poison future calls');
 const later=await runSkillTools(heldInput);assert.match(later.context,/true/);
 const {listUncertainToolCalls,reconcileToolCall}=await import('./external-tool-guard.js');
 const uncertain=listUncertainToolCalls().filter(r=>r.toolName===name);assert.equal(uncertain.length,2);
 const beforeResolve=calls;for(const item of uncertain)reconcileToolCall({...item,outcome:'not_executed',confirmed:true,note:'已核对服务端记录，确认未执行'});
 assert.equal(calls,beforeResolve,'resolution never dispatches');
 assert.equal((database.prepare("SELECT COUNT(*) AS n FROM skill_tool_executions WHERE tool_name=? AND status='unknown'").get(name) as any).n,0);
 assert.equal((database.prepare("SELECT status FROM action_proposals WHERE id=?").get(pending.pending[0].id) as any).status,'reconciled');
 assert.throws(()=>confirmAction(pending.pending[0].id),/已经执行|关闭/);
 saveToolPolicy(name,'auto');await assert.rejects(runSkillTools(input),{code:'TOOL_OUTCOME_UNKNOWN'});assert.equal(calls,beforeResolve+1,'a new explicit request can dispatch after reconciliation');


});
