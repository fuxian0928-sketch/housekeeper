import assert from 'node:assert/strict';
import test from 'node:test';
import {mkdtempSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {createServer} from 'node:http';

test('HTTP tool lifecycle: schema, secret, preview, confirmation, continuation, disabled dependencies and revision invalidation',async t=>{
 const root=mkdtempSync(join(tmpdir(),'xiaoe-lifecycle-'));
 process.env.AI_SECRETARY_DB_PATH=join(root,'test.db');process.env.AI_SECRETARY_SKILLS_DIR=join(root,'skills');
 const {database,initializeDatabase}=await import('../../db.js');initializeDatabase();
 let calls=0;
 const server=createServer(async(req,res)=>{
  assert.equal(req.headers.authorization,'Bearer fixture-secret');
  let body='';for await(const chunk of req)body+=chunk;
  calls++;res.setHeader('Content-Type','application/json');res.end(JSON.stringify({text:JSON.parse(body).query,source:'fixture'}));
 });
 await new Promise<void>(r=>server.listen(0,'127.0.0.1',r));
 t.after(()=>{server.closeAllConnections();server.close();database.close();});
 const {port}=server.address() as {port:number};
 const http=await import('./http-tools.js');
 const {listSkillTools}=await import('./skill-tool-registry.js');
 const {buildManagedSkill,listManagedSkills}=await import('./skill-manager.js');
 const work=await import('./skill-workbench.js');
 const {saveToolEnabled}=await import('./tool-controls.js');
 const {runSkillTools}=await import('./skill-executor.js');
 const {confirmAction,cancelAction}=await import('../../actions/action-service.js');
 const definition={name:'测试接口',description:'读取测试信息',method:'POST',url:`http://127.0.0.1:${port}/echo`,token:'fixture-secret',schema:{type:'object',properties:{query:{type:'string'}},required:['query'],additionalProperties:false}};
 const tool=http.saveHttpTool(definition);
 assert.ok(listSkillTools().some(x=>x.name===tool.toolName));
 assert.ok(!JSON.stringify(http.listHttpTools()).includes('fixture-secret'));
 assert.ok(!String(database.prepare('SELECT secret FROM custom_http_tools').get()?.secret).includes('fixture-secret'));
 await assert.rejects(()=>http.callHttpTool(tool.toolName,{query:7}),/Schema/);assert.equal(calls,0);
 const skill=await buildManagedSkill({name:'接口测试',description:'读取信息后继续分析',instructions:'通过接口查询，然后根据实际结果继续。'});
 work.saveSkillRequirements(skill.id,[tool.toolName]);
 const check=await work.inspectSkill(skill.id,async()=>JSON.stringify({tools:[tool.toolName],missingCapabilities:[]}));assert.equal(check.status,'dependencies_available');
 const planner=async()=>JSON.stringify({toolCalls:[{tool:tool.toolName,arguments:{query:'hello'}}]});
 const preview=await work.runSkillWorkbench(skill.id,{message:'查询hello',mode:'preview'},planner);
 assert.match(preview.context,/预览，未执行/);assert.equal(calls,0);assert.equal(preview.pending.length,0);
 assert.equal(database.prepare('SELECT count(*) AS n FROM action_proposals').get()?.n,0);
 await assert.rejects(()=>work.runSkillWorkbench(skill.id,{message:'查询hello',mode:'execute'},planner),/确认/);
 const actual=await work.runSkillWorkbench(skill.id,{message:'查询hello',mode:'execute',confirm:true},planner);
 assert.equal(actual.pending.length,1);assert.equal(calls,0);
 await assert.rejects(()=>work.resumeSkillWorkbench(skill.id,actual.runId,planner),/先确认/);
 await confirmAction(actual.pending[0].id);assert.equal(calls,1);
 await confirmAction(actual.pending[0].id);assert.equal(calls,1);
 assert.equal(work.skillWorkbenchRuns(skill.id).find(r=>r.id===actual.runId)?.status,'ready_to_continue');
 const finished=await work.resumeSkillWorkbench(skill.id,actual.runId,async raw=>{
  assert.match(raw,/hello/);assert.match(raw,/fixture/);
  // An accidental repeated write is suppressed across confirmation rounds.
  return planner();
 });
 assert.equal(finished.pending.length,0);assert.equal(calls,1);
 assert.equal(work.skillWorkbenchRuns(skill.id).find(r=>r.id===actual.runId)?.status,'finished');
 await assert.rejects(()=>work.resumeSkillWorkbench(skill.id,actual.runId,planner),/没有可继续/);
 const cancelled=await work.runSkillWorkbench(skill.id,{message:'查询hello',mode:'execute',confirm:true},planner);
 cancelAction(cancelled.pending[0].id);
 assert.equal(work.skillWorkbenchRuns(skill.id).find(r=>r.id===cancelled.runId)?.status,'cancelled');
 saveToolEnabled(tool.toolName,false);
 assert.equal((await work.inspectSkill(skill.id)).status,'blocked');
 await assert.rejects(()=>work.runSkillWorkbench(skill.id,{message:'查询',mode:'preview'},planner),/不可用/);
 await assert.rejects(()=>runSkillTools({message:'查询',conversationId:'none',skills:listManagedSkills().filter(s=>s.id===skill.id),skillInstruction:'',context:{vaultPath:'central://documents'},complete:planner}),/依赖不可用/);
 saveToolEnabled(tool.toolName,true);
 const stale=await work.runSkillWorkbench(skill.id,{message:'查询hello',mode:'execute',confirm:true},planner);
 const changed=http.saveHttpTool({...definition,token:''},tool.id);
 assert.notEqual(changed.toolName,tool.toolName);assert.equal(changed.hasToken,true);
 await assert.rejects(async()=>confirmAction(stale.pending[0].id),/不存在|修改|删除|未注册/);
 assert.equal(calls,1);assert.equal((await work.inspectSkill(skill.id)).status,'blocked');
 http.deleteHttpTool(tool.id);assert.equal(http.listHttpTools().length,0);
 assert.throws(()=>http.saveHttpTool({...definition,url:'https://example.com/?key=secret'}),/地址/);
 assert.throws(()=>http.saveHttpTool({...definition,schema:{type:'string'}}),/object/);
});
