import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
test('dispatch claim spans conversations, canonical arguments, concurrent calls and crash recovery',async t=>{
 process.env.AI_SECRETARY_DB_PATH=join(mkdtempSync(join(tmpdir(),'dispatch-guard-')),'test.db');
 const {database,initializeDatabase}=await import('../../db.js');initializeDatabase();t.after(()=>database.close());
 const {guardedExternalTool:run,listUncertainToolCalls,reconcileToolCall}=await import('./external-tool-guard.js');const {unknownToolOutcome}=await import('./tool-outcome.js');
 let calls=0,release!:(value:string)=>void;
 const first=run('http_fixture',{b:2,a:{z:1,y:2}},()=>{calls++;return new Promise<string>(r=>release=r);});
 await assert.rejects(run('http_fixture',{a:{y:2,z:1},b:2},async()=>{calls++;return 'bad';}),{code:'TOOL_IN_PROGRESS'});assert.equal(calls,1);
 const active=listUncertainToolCalls().find(r=>r.toolName==='http_fixture')!;assert.equal(active.canResolve,false);
 assert.throws(()=>reconcileToolCall({...active,confirmed:true,outcome:'not_executed',note:'已核对'}),/仍在执行/);
 release('ok');assert.equal(await first,'ok');assert.equal(await run('http_fixture',{b:2,a:{z:1,y:2}},async()=> 'new explicit call'),'new explicit call');
 await assert.rejects(run('mcp_fixture',{x:1},async()=>{throw unknownToolOutcome();}),{code:'TOOL_OUTCOME_UNKNOWN'});
 await assert.rejects(run('mcp_fixture',{x:1},async()=>{calls++;return 'bad';}),{code:'TOOL_OUTCOME_UNKNOWN'});assert.equal(calls,1);
 await assert.rejects(run('http_failed',{},async()=>{throw Error('validation');}),/validation/);assert.equal(await run('http_failed',{},async()=> 'ok'),'ok');
 database.prepare("UPDATE external_tool_dispatches SET status='running' WHERE tool_name='http_failed'").run();
 await assert.rejects(run('http_failed',{},async()=>{calls++;return 'bad';}),{code:'TOOL_OUTCOME_UNKNOWN'});assert.equal(calls,1);
 const unknown=listUncertainToolCalls().find(r=>r.toolName==='mcp_fixture')!;
 assert.throws(()=>reconcileToolCall({...unknown,outcome:'not_executed',note:'已核对'}),/明确核对/);
 assert.throws(()=>reconcileToolCall({...unknown,attemptId:'stale',confirmed:true,outcome:'not_executed',note:'服务端没有记录'}),/状态已变化/);
 const result=reconcileToolCall({...unknown,confirmed:true,outcome:'not_executed',note:'服务端没有记录'});assert.equal(result.retried,false);assert.equal(calls,1);
 assert.throws(()=>reconcileToolCall({...unknown,confirmed:true,outcome:'not_executed',note:'服务端没有记录'}),/状态已变化/);
 assert.equal(await run('mcp_fixture',{x:1},async()=> 'explicit retry'),'explicit retry');
 assert.equal((database.prepare('SELECT COUNT(*) AS n FROM external_tool_resolutions').get() as any).n,1);
 const rows=database.prepare('SELECT * FROM external_tool_dispatches').all();assert.equal(JSON.stringify(rows).includes('arguments'),false);
});
