import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';

test('project adapter preserves hybrid/core selections, evidence and read-only semantics',async()=>{
 process.env.AI_SECRETARY_DB_PATH=join(mkdtempSync(join(tmpdir(),'project-provider-')),'test.db');
 const {database,initializeDatabase,sqliteVecAvailable}=await import('../../db.js');initializeDatabase();
 const {ProjectMemoryContextProvider,projectMemoryProfileRevision}=await import('./project-memory-context.js');
 const {getCoreMemorySnapshot,searchRelevantMemories}=await import('./memory-service.js');
 const stamp=new Date().toISOString();
 try{
  for(const id of ['p1','p2'])database.prepare(`INSERT INTO projects(id,name,vault_path,source_path,created_at,updated_at) VALUES(?,?, '', '',?,?)`).run(id,id,stamp,stamp);
  const insert=database.prepare(`INSERT INTO memories(id,project_id,content,memory_type,status,source_id,source_label,source_excerpt,created_at,updated_at,supersedes_id,contradicts_json) VALUES(?,?,?,?,'confirmed','source','原始记录','来源摘录',?,?,'old','["other",2,"other"]')`);
  for(let i=0;i<24;i++)insert.run(`m${i}`,i===0?null:'p1',`项目约束 ${i}`,i<19?'preference':'fact',stamp,stamp);
  insert.run('other','p2','不属于当前项目','preference',stamp,stamp);
  assert.equal(sqliteVecAvailable,true);
  const vector=Array(1024).fill(.02);database.prepare(`INSERT INTO memory_vectors(memory_id,embedding) VALUES('m23',?)`).run(JSON.stringify(vector));
  let calls=0;const embedding={model:'fixture',dimension:1024,version:'fixture',async embed(){calls++;return [vector];}};
  const request={query:'当前项目设计约束',projectIds:['p1'],limit:32};
  const before=database.prepare('SELECT revision FROM memory_context_revision').get()?.revision;
  const expectedRelevant=await searchRelevantMemories(request.query,'p1',embedding,8,undefined,{trackAccess:false});
  const expectedCore=getCoreMemorySnapshot('p1');
  const result=await new ProjectMemoryContextProvider(embedding).retrieve(request);
  assert.equal(calls,2);assert.equal(result.provider,'existing-project-hybrid-v1');
  const all=[...result.facts,...result.preferences];
  assert.deepEqual(all.filter(m=>m.relevantRank!==undefined).sort((a,b)=>a.relevantRank!-b.relevantRank!).map(m=>m.memoryId),expectedRelevant.map(m=>m.id));
  assert.deepEqual(all.filter(m=>m.coreRank!==undefined).sort((a,b)=>a.coreRank!-b.coreRank!).map(m=>m.memoryId),expectedCore.map(m=>m.id));
  assert.equal(all.length,new Set(all.map(m=>m.memoryId)).size);assert.ok(!all.some(m=>m.memoryId==='other'));
  assert.ok(all.every(m=>m.sourceId==='source'&&m.sourceExcerpt==='来源摘录'&&m.supersedesId==='old'));
  assert.ok(all.every(m=>JSON.stringify(m.contradictsIds)==='["other"]'));
  assert.equal(database.prepare('SELECT revision FROM memory_context_revision').get()?.revision,before);
  assert.equal(database.prepare('SELECT SUM(access_count) AS n FROM memories').get()?.n,0);
  await new ProjectMemoryContextProvider(embedding,true).retrieve(request);
  assert.equal(database.prepare('SELECT SUM(access_count) AS n FROM memories').get()?.n,8);
  const small=await new ProjectMemoryContextProvider().retrieve({...request,limit:2});assert.equal(small.facts.length+small.preferences.length,2);
  for(const projectIds of [[],['p1','p2'],['missing']])await assert.rejects(new ProjectMemoryContextProvider().retrieve({...request,projectIds}),/MEMORY_PROJECT_/);
  await assert.rejects(new ProjectMemoryContextProvider().retrieve({...request,limit:33}),/LIMIT/);
  const abort=new AbortController();abort.abort();await assert.rejects(new ProjectMemoryContextProvider().retrieve({...request,signal:abort.signal}),{name:'AbortError'});
  const {VoicePrefetchCandidates}=await import('./voice-prefetch-candidates.js');
  const {buildProjectContext}=await import('../../orchestration/context-builder.js');
  const {routeWorkIntents}=await import('../../orchestration/intent-router.js');
  let model='fixture', key='test-key';
  const cache=new VoicePrefetchCandidates(undefined,Date.now,()=>({provider:new ProjectMemoryContextProvider(embedding),revision:projectMemoryProfileRevision('https://fixture.invalid',model,key)}));
  const prefetchRequest={query:request.query,mode:'work' as const,projectId:'p1',conversationId:'c1'};
  const signal=new AbortController().signal;
  const ready=await cache.prepare(prefetchRequest,signal);
  database.prepare(`INSERT INTO conversations(id,scope_type,title,created_at,updated_at) VALUES('unrelated','memory','unrelated',?,?)`).run(stamp,stamp);
  database.prepare(`INSERT INTO self_diagnostics(id,request_id,stage,status,elapsed_ms,created_at) VALUES('d','r','intent','done',1,?)`).run(stamp);
  const cached=cache.consume(ready.token,prefetchRequest);assert.ok(cached);
  assert.equal(cached.provider,'existing-project-hybrid-v1');
  const beforeCalls=calls;
  const beforeAccess=Number(database.prepare('SELECT SUM(access_count) AS n FROM memories').get()?.n);
  const built=await buildProjectContext('p1',request.query,null,routeWorkIntents('项目进展','p1',[]),embedding,signal,cached);
  assert.equal(calls,beforeCalls,'cached project memory must avoid another embedding call');
  assert.equal((built.snapshot.memoryContext as {provider:string}).provider,'existing-project-hybrid-v1');
  assert.equal(database.prepare('SELECT SUM(access_count) AS n FROM memories').get()?.n,beforeAccess+8);
  const configChanged=await cache.prepare(prefetchRequest,signal);model='changed';assert.equal(cache.consume(configChanged.token,prefetchRequest),undefined);
  const credentialChanged=await cache.prepare(prefetchRequest,signal);key='changed-key';assert.equal(cache.consume(credentialChanged.token,prefetchRequest),undefined);
  const indexChanged=await cache.prepare(prefetchRequest,signal);
  const {syncMemorySearch}=await import('./memory-service.js');
  syncMemorySearch('m23');
  assert.equal(cache.consume(indexChanged.token,prefetchRequest),undefined);
  database.prepare(`INSERT INTO memory_vectors(memory_id,embedding) VALUES('m23',?)`).run(JSON.stringify(vector));
  const during=new VoicePrefetchCandidates(undefined,Date.now,()=>({provider:new ProjectMemoryContextProvider({...embedding,async embed(){model='changed-during-request';return [vector];}}),revision:projectMemoryProfileRevision('https://fixture.invalid',model,key)}));
  await assert.rejects(during.prepare(prefetchRequest,signal),/PROFILE_CHANGED/);
  const deleted={...embedding,async embed(){database.prepare(`UPDATE projects SET deleted_at=? WHERE id='p1'`).run(stamp);return [vector];}};
  const count=database.prepare('SELECT SUM(access_count) AS n FROM memories').get()?.n;
  await assert.rejects(new ProjectMemoryContextProvider(deleted,true).retrieve(request),/PROJECT_UNAVAILABLE/);
  assert.equal(database.prepare('SELECT SUM(access_count) AS n FROM memories').get()?.n,count);
 }finally{database.close();}
});
