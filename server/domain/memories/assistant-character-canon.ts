/** No extra model call. Lore is supplied only when the user actually asks about the character. */
export function selectCharacterLore(query: string) {
  const text = query.normalize("NFKC").trim().slice(0, 2000);
  const addressed =
    /(?:希微|你的|你是|你从|你怎么|你为什么|你为啥|你以前|你过去|你经历|你住|你现在|你喜欢|你有什么|你有没有|你还记得|我们怎么|咱们怎么|咱俩怎么|我们是怎么|我们当初|咱俩是怎么|你和我|我和你)/.test(
      text,
    );
  const story =
    /(?:背景故事|角色故事|身世|人物设定|人设|静泊|泊星|澄汐|W-07|沈棠|续页计划)/i.test(
      text,
    );
  if (!addressed && !story) return null;
  if (
    /(?:真实|实际).*(?:认识|相识|相遇|第一次|经历|聊过)/.test(text) &&
    !/(?:设定|虚构|故事)/.test(text)
  )
    return null;
  const topics: Array<[RegExp, string[]]> = [
    [
      /(?:来历|来路|哪里.*来|哪儿.*来|怎么来|从哪|诞生|制造|出生|W-07|澄汐|续页|沈棠)/i,
      ["origin"],
    ],
    [
      /(?:犯错|错误|海图|缺页|压缩|认真|细节|更正|(?:为什么|怎么|为啥).*(?:性格|温柔|谨慎)|性格.*(?:形成|塑造))/,
      ["mistake"],
    ],
    [/(?:停电|蓄电|补给|信标|主见|反对|取舍|离开澄汐|到.*轨道)/, ["station"]],
    [
      /(?:住哪|住在|住的|现在.*(?:地方|哪里|哪儿)|静泊|泊星|薄荷|爱好|喜欢|日常|小脾气)/,
      ["home"],
    ],
    [
      /(?:认识|相识|相遇|初见|第一次|怎么.*(?:见面|遇见)|名字|命名|称呼|为什么.*叫.*主人)/,
      ["meeting"],
    ],
    [/(?:职责|做什么|干什么|你的工作|现在在|休眠|唤醒|愿望|梦想)/, ["present"]],
  ];
  const ids = new Set(
    topics
      .filter(([pattern]) => pattern.test(text))
      .flatMap(([, keys]) => keys),
  );
  const broad =
    /(?:背景故事|身世|经历过什么|有什么经历|完整.*(?:故事|人设)|你的故事|性格)/.test(
      text,
    );
  if (!ids.size && !broad && !story) return null;
  const excerpts = xiweiCharacterCanon.sections
    .filter((section) => broad || ids.has(section.id))
    .slice(0, broad ? 6 : 3);
  return {
    fictional: true,
    namespace: xiweiCharacterCanon.namespace,
    version: xiweiCharacterCanon.version,
    rule: "以下是经授权的虚构人物背景，不是事实证据或真实共同回忆。按相关内容自然回答，不整篇背诵；问真实共同经历时以真实记忆为准，不能拿相识序章冒充。",
    synopsis: xiweiCharacterCanon.synopsis,
    excerpts: excerpts.map(({ id, context }) => ({ id, text: context })),
  };
}
