import test from 'node:test';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { mkdtemp, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

test('中央文档同步保留多设备来源并按内容哈希去重', async () => {
  const directory = await mkdtemp(join(tmpdir(), 'ai-secretary-central-sync-'));
  process.env.AI_SECRETARY_DB_PATH = join(directory, 'central.db');
  process.env.AI_SECRETARY_DOCUMENT_ROOT = join(directory, 'raw');
  process.env.AI_SECRETARY_PROCESSED_ROOT = join(directory, 'processed');
  const { database, initializeDatabase } = await import('../db.js');
  initializeDatabase();
  const { acceptCentralDocument, centralSyncStatus, compareCentralManifest, deleteCentralDocument } = await import('./central-document-service.js');
  const content = Buffer.from('# 同一篇文档\n\n这是两台电脑同步后的相同原文。', 'utf8');
  const contentHash = createHash('sha256').update(content).digest('hex');
  const common = { vaultId: 'vault-shared-001', vaultName: '共享仓库', knowledgePrefix: '', path: '项目/计划.md', contentBase64: content.toString('base64'), contentHash, modifiedAt: '2026-08-30T12:00:00.000Z' };
  const first = await acceptCentralDocument({ ...common, deviceId: 'device-home-001', deviceName: '家里电脑', platform: 'win32' });
  const second = await acceptCentralDocument({ ...common, deviceId: 'device-work-001', deviceName: '公司电脑', platform: 'win32' });
  assert.equal(first.accepted, true);
  assert.equal(first.deduplicated, false);
  assert.equal(second.accepted, true);
  assert.equal(second.deduplicated, true);
  assert.equal(first.sourceDocumentId, second.sourceDocumentId);
  assert.deepEqual(centralSyncStatus(), { devices: 2, vaults: 1, sourceDocuments: 1, rawBlobs: 1, versions: 2, conflicts: 0, pendingCommands: 0 });
  assert.equal((database.prepare('SELECT COUNT(*) AS count FROM knowledge_documents').get() as { count: number }).count, 1);
  const blob = database.prepare('SELECT storage_path FROM central_document_blobs WHERE content_hash=?').get(contentHash) as { storage_path: string };
  assert.deepEqual(await readFile(join(process.env.AI_SECRETARY_DOCUMENT_ROOT, blob.storage_path)), content);
  const nextContent = Buffer.from('# 同一篇文档\n\n这是家里电脑修改后的新版本。', 'utf8');
  const nextHash = createHash('sha256').update(nextContent).digest('hex');
  const changed = await acceptCentralDocument({ ...common, deviceId: 'device-home-001', deviceName: '家里电脑', contentBase64: nextContent.toString('base64'), contentHash: nextHash, baseHash: contentHash, modifiedAt: '2026-08-30T12:05:00.000Z' });
  assert.equal(changed.accepted, true);
  const workManifest = compareCentralManifest({ deviceId: 'device-work-001', deviceName: '公司电脑', platform: 'win32', vaultId: common.vaultId, vaultName: common.vaultName, files: [{ path: common.path, hash: contentHash, baseHash: contentHash, bytes: content.length, modifiedAt: common.modifiedAt }] });
  assert.deepEqual(workManifest.upload, []);
  assert.deepEqual(workManifest.remote, []);
  assert.deepEqual(workManifest.deleted, []);
  assert.equal((database.prepare('SELECT COUNT(*) AS count FROM knowledge_documents').get() as { count: number }).count, 1);
  const removed = deleteCentralDocument({ deviceId: 'device-home-001', deviceName: '家里电脑', platform: 'win32', vaultId: common.vaultId, vaultName: common.vaultName, path: common.path, baseHash: nextHash });
  assert.equal(removed.deleted, true);
  assert.equal(removed.retainedOnServer, true);
  assert.equal((database.prepare('SELECT COUNT(*) AS count FROM knowledge_documents').get() as { count: number }).count, 1);
  assert.deepEqual(centralSyncStatus(), { devices: 2, vaults: 1, sourceDocuments: 1, rawBlobs: 2, versions: 3, conflicts: 0, pendingCommands: 0 });
  database.close();
  await rm(directory, { recursive: true, force: true });
});
